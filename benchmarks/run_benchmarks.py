# benchmarks/run_benchmarks.py
"""
Run all univariate detectors against synthetic fixtures.
Outputs precision/recall/F1 to docs/benchmarks.md.

Usage:
  uv run python benchmarks/run_benchmarks.py
"""
from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np

_REPO_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(_REPO_ROOT / "packages" / "dqt" / "src"))
sys.path.insert(0, str(_REPO_ROOT))

import dqt  # noqa: F401 — triggers detector registration

from benchmarks.fixtures import make_fixtures
from dqt.algorithms._base import Verdict
from dqt.algorithms._registry import registry

_SKIP = {
    "isolation_forest_fraction", "mahalanobis_distance", "lof", "hbos", "ecod",
    "one_class_svm", "callable_check", "remote_check", "bocpd", "matrix_profile",
    "prophet_anomaly", "adwin",
    # Aggregate detectors — require pre-aggregated input shape, not raw floats
    "completeness", "uniqueness", "validity", "null_fraction", "numeric_mean",
    "volume", "row_count_in_range", "freshness_seconds_behind", "schema_change",
    "referential_integrity_rate", "outlier_fraction_drift",
    "cardinality_in_range", "sum_in_range", "stddev_in_range", "min_in_range",
    "max_in_range", "quantile_in_range", "median_in_range",
    # String / date / categorical detectors require non-numeric input
    "regex_match", "date_format", "string_case_violation", "string_length_range",
    "set_membership", "set_exclusion", "value_in_range", "date_part_missing_fraction",
    "sql_assertion_violation",
    # Multivariate association detectors
    "mutual_information", "cramers_v", "column_pair_comparison", "composite_uniqueness",
}


def run_all() -> None:
    rng = np.random.default_rng(0)
    fixtures = make_fixtures(rng)
    rows: list[tuple] = []

    for slug in sorted(registry.slugs()):
        if slug in _SKIP:
            continue
        cls = registry.get(slug)
        tp = fp = fn = tn = 0
        for fix in fixtures:
            try:
                det = cls()
                with warnings.catch_warnings():
                    warnings.simplefilter("ignore")
                    state = det.fit(fix.reference)
                    r_clean = det.score(fix.current_clean, state)
                    r_anom = det.score(fix.current_anomalous, state)
                if r_clean.verdict == Verdict.pass_:
                    tn += 1
                else:
                    fp += 1
                if r_anom.verdict != Verdict.pass_:
                    tp += 1
                else:
                    fn += 1
            except Exception:
                continue

        total = tp + fp + fn + tn
        if total == 0:
            continue
        precision = tp / (tp + fp) if (tp + fp) > 0 else float("nan")
        recall = tp / (tp + fn) if (tp + fn) > 0 else float("nan")
        f1 = (2 * precision * recall / (precision + recall)
              if (precision + recall) > 0 else float("nan"))
        fpr = fp / (fp + tn) if (fp + tn) > 0 else float("nan")

        def _fmt(v: float) -> str:
            return f"{v:.2f}" if v == v else "—"  # noqa: PLR0124 (nan check)

        rows.append((slug, tp, fp, fn, tn, _fmt(precision), _fmt(recall), _fmt(f1), _fmt(fpr)))

    # ── CSV output ────────────────────────────────────────────────────────────
    csv_path = _REPO_ROOT / "examples" / "benchmarks" / "results.csv"
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    csv_lines = ["slug,tp,fp,fn,tn,precision,recall,f1,fpr"]
    for r in rows:
        csv_lines.append(f"{r[0]},{r[1]},{r[2]},{r[3]},{r[4]},{r[5]},{r[6]},{r[7]},{r[8]}")
    csv_path.write_text("\n".join(csv_lines) + "\n", encoding="utf-8")
    print(f"examples/benchmarks/results.csv updated — {len(rows)} detectors")

    # ── Markdown table ────────────────────────────────────────────────────────
    header = "| Detector | TP | FP | FN | TN | Precision | Recall | F1 | FPR |\n"
    sep = "|---|---|---|---|---|---|---|---|---|\n"
    body = "".join(
        f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[7]} | {r[8]} |\n"
        for r in rows
    )
    out = (
        "# dqt Detector Benchmarks\n\n"
        "_Auto-generated by `benchmarks/run_benchmarks.py`. "
        "Do not edit — re-run to update._\n\n"
        "Fixtures: normal mean-shift, lognormal tail-shift, 5% outlier injection, "
        "10% null injection. N=500 rows each.\n\n"
        "Raw results: [`examples/benchmarks/results.csv`]"
        "(../examples/benchmarks/results.csv)\n\n"
        f"{header}{sep}{body}"
    )
    docs_path = _REPO_ROOT / "docs" / "benchmarks.md"
    docs_path.write_text(out, encoding="utf-8")
    print(f"docs/benchmarks.md updated — {len(rows)} detectors benchmarked")


if __name__ == "__main__":
    run_all()
