"""Generate benchmark summary markdown and update README Quality section numbers.

Usage:
    python scripts/generate_benchmark_summary.py

Reads:
    examples/benchmarks/results.csv

Writes:
    examples/benchmarks/results_summary.md   (grouped detector table)
    packages/dqt/README.md                   (updates NUMBERS_START/NUMBERS_END markers)

Idempotent -- safe to re-run.
"""
from __future__ import annotations

import csv
import re
import statistics
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
CSV_PATH = REPO_ROOT / "examples" / "benchmarks" / "results.csv"
SUMMARY_MD_PATH = REPO_ROOT / "examples" / "benchmarks" / "results_summary.md"
README_PATH = REPO_ROOT / "packages" / "dqt" / "README.md"

NUMBERS_START = "<!-- NUMBERS_START -->"
NUMBERS_END = "<!-- NUMBERS_END -->"

# Group display order and labels
GROUP_ORDER = [
    ("basic", "Basic"),
    ("drift", "Drift"),
    ("outliers_uni", "Univariate Outliers"),
    ("outliers_multi", "Multivariate Outliers"),
    ("timeseries", "Time Series"),
    ("info", "Information Theory"),
    ("pattern", "Pattern"),
    ("referential", "Referential"),
    ("schema", "Schema"),
    ("custom", "Custom"),
]


def _slug_to_group(slug: str) -> str:
    """Look up the group for a slug via the detector registry."""
    import sys
    sys.path.insert(0, str(REPO_ROOT / "packages" / "dqt" / "src"))
    import dqt.algorithms.basic  # noqa: F401
    import dqt.algorithms.custom  # noqa: F401
    import dqt.algorithms.drift  # noqa: F401
    import dqt.algorithms.info  # noqa: F401
    import dqt.algorithms.outliers_multi  # noqa: F401
    import dqt.algorithms.outliers_uni  # noqa: F401
    import dqt.algorithms.pattern  # noqa: F401
    import dqt.algorithms.referential  # noqa: F401
    import dqt.algorithms.schema  # noqa: F401
    import dqt.algorithms.timeseries  # noqa: F401
    from dqt.algorithms._registry import registry
    try:
        return registry.get(slug).group
    except KeyError:
        return "unknown"


def _build_group_map(slugs: list[str]) -> dict[str, str]:
    """Return {slug: group} for all slugs. Imports registry once."""
    import sys
    sys.path.insert(0, str(REPO_ROOT / "packages" / "dqt" / "src"))
    import dqt.algorithms.basic  # noqa: F401
    import dqt.algorithms.custom  # noqa: F401
    import dqt.algorithms.drift  # noqa: F401
    import dqt.algorithms.info  # noqa: F401
    import dqt.algorithms.outliers_multi  # noqa: F401
    import dqt.algorithms.outliers_uni  # noqa: F401
    import dqt.algorithms.pattern  # noqa: F401
    import dqt.algorithms.referential  # noqa: F401
    import dqt.algorithms.schema  # noqa: F401
    import dqt.algorithms.timeseries  # noqa: F401
    from dqt.algorithms._registry import registry
    result = {}
    for slug in slugs:
        try:
            result[slug] = registry.get(slug).group
        except KeyError:
            result[slug] = "unknown"
    return result


def read_csv() -> list[dict]:
    rows = []
    with open(CSV_PATH, newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            rows.append(row)
    return rows


def generate_summary_md(rows: list[dict], group_map: dict[str, str]) -> str:
    # Organise by group
    by_group: dict[str, list[dict]] = {}
    for row in rows:
        g = group_map.get(row["detector_slug"], "unknown")
        by_group.setdefault(g, []).append(row)

    lines: list[str] = [
        "# Benchmark Results",
        "",
        "Per-detector benchmark results against labeled synthetic datasets.",
        "Generated by `scripts/generate_benchmark_summary.py` -- do not edit manually.",
        "",
    ]

    for group_key, group_label in GROUP_ORDER:
        group_rows = sorted(by_group.get(group_key, []), key=lambda r: r["detector_slug"])
        if not group_rows:
            continue
        lines.append(f"## {group_label}")
        lines.append("")
        lines.append("| Detector | Dataset | Precision | Recall | F1 | Time (s) |")
        lines.append("| --- | --- | --- | --- | --- | --- |")
        for r in group_rows:
            slug = r["detector_slug"]
            dataset = r["dataset"]
            precision = f"{float(r['precision']):.4f}"
            recall = f"{float(r['recall']):.4f}"
            f1 = f"{float(r['f1']):.4f}"
            time_s = f"{float(r['wall_time_s']):.4f}"
            lines.append(f"| `{slug}` | {dataset} | {precision} | {recall} | {f1} | {time_s} |")
        lines.append("")

    # Handle any unknown-group rows
    unknown_rows = sorted(by_group.get("unknown", []), key=lambda r: r["detector_slug"])
    if unknown_rows:
        lines.append("## Unknown Group")
        lines.append("")
        lines.append("| Detector | Dataset | Precision | Recall | F1 | Time (s) |")
        lines.append("| --- | --- | --- | --- | --- | --- |")
        for r in unknown_rows:
            slug = r["detector_slug"]
            dataset = r["dataset"]
            precision = f"{float(r['precision']):.4f}"
            recall = f"{float(r['recall']):.4f}"
            f1 = f"{float(r['f1']):.4f}"
            time_s = f"{float(r['wall_time_s']):.4f}"
            lines.append(f"| `{slug}` | {dataset} | {precision} | {recall} | {f1} | {time_s} |")
        lines.append("")

    return "\n".join(lines)


def compute_numbers(rows: list[dict]) -> tuple[float, int, int, int]:
    """Return (median_f1, count_f1_ge_0_8, count_f1_ge_0_6, total)."""
    f1_values = [float(r["f1"]) for r in rows]
    total = len(f1_values)
    median_f1 = statistics.median(f1_values)
    count_ge_08 = sum(1 for v in f1_values if v >= 0.8)
    count_ge_06 = sum(1 for v in f1_values if v >= 0.6)
    return median_f1, count_ge_08, count_ge_06, total


def update_readme(median_f1: float, count_ge_08: int, count_ge_06: int, total: int) -> None:
    content = README_PATH.read_text(encoding="utf-8")
    new_numbers_line = (
        f"Median F1: {median_f1:.2f} | "
        f"Detectors with F1 >= 0.8: {count_ge_08}/{total} | "
        f"Detectors with F1 >= 0.6: {count_ge_06}/{total}"
    )
    pattern = re.compile(
        r"(" + re.escape(NUMBERS_START) + r"\n)"
        r".*?"
        r"(\n" + re.escape(NUMBERS_END) + r")",
        re.DOTALL,
    )
    replacement = r"\g<1>" + new_numbers_line + r"\g<2>"
    updated, count = re.subn(pattern, replacement, content)
    if count == 0:
        raise RuntimeError(
            f"Could not find {NUMBERS_START} ... {NUMBERS_END} markers in {README_PATH}"
        )
    README_PATH.write_text(updated, encoding="utf-8")


def main() -> None:
    rows = read_csv()
    slugs = [r["detector_slug"] for r in rows]
    group_map = _build_group_map(slugs)

    summary_md = generate_summary_md(rows, group_map)
    SUMMARY_MD_PATH.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_MD_PATH.write_text(summary_md, encoding="utf-8")
    print(f"Written: {SUMMARY_MD_PATH}")

    median_f1, count_ge_08, count_ge_06, total = compute_numbers(rows)
    update_readme(median_f1, count_ge_08, count_ge_06, total)
    print(f"Updated: {README_PATH}")
    print(
        f"Numbers: median F1={median_f1:.4f}, "
        f"F1>=0.8: {count_ge_08}/{total}, "
        f"F1>=0.6: {count_ge_06}/{total}"
    )


if __name__ == "__main__":
    main()
